  ar:{heading:'الوقت المتبقي للقاء',done:'حان موعد اللقاء التعريفي',foot:'السبت 28 نوفمبر · بيروت 7م · مكة 8م · UTC 17',units:['أيام','ساعات','دقائق','ثوانٍ']},
